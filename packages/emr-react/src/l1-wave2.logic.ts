export function themeColorWithAlpha(color: string, alpha: number): string {
  const hex = color.trim();
  const match = /^#([0-9a-fA-F]{6})$/.exec(hex);
  if (match) {
    const num = Number.parseInt(match[1]!, 16);
    const r = (num >> 16) & 255;
    const g = (num >> 8) & 255;
    const b = num & 255;
    return `rgba(${r}, ${g}, ${b}, ${alpha})`;
  }
  const short = /^#([0-9a-fA-F]{3})$/.exec(hex);
  if (short) {
    const s = short[1]!;
    const r = Number.parseInt(s[0]! + s[0]!, 16);
    const g = Number.parseInt(s[1]! + s[1]!, 16);
    const b = Number.parseInt(s[2]! + s[2]!, 16);
    return `rgba(${r}, ${g}, ${b}, ${alpha})`;
  }
  return color;
}

/** Formats byte count cleanly for L1 image upload cards without upward L2 imports. */
export function formatL1ByteSize(sizeBytes?: number): string {
  if (sizeBytes === undefined || !Number.isFinite(sizeBytes) || sizeBytes < 0) return '';
  if (sizeBytes < 1024) return `${Math.round(sizeBytes)} B`;
  if (sizeBytes < 1024 * 1024) return `${(sizeBytes / 1024).toFixed(1)} KB`;
  return `${(sizeBytes / (1024 * 1024)).toFixed(1)} MB`;
}
