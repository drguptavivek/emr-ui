/**
 * Hand-written, verified catalog of every public EMR UI component and directive.
 *
 * Layers (see docs/catalog and packages/emr-ui/src/lib/catalog.spec.ts for the
 * fitness test that keeps this manifest honest):
 *   1 primitives  - mechanical input, feedback, layout. No clinical meaning.
 *   2 fields      - bind a ClinicalFieldDefinition to a primitive.
 *   3 structures  - schema-driven containers.
 *   4 domain      - clinical semantics.
 *   6 authoring   - meta-layer producing L2-L5 definitions.
 * (0 = foundations tokens, 5 = data-only recipes; neither currently has catalog entries.)
 *
 * A module may import from its OWN layer or any LOWER layer, never upward.
 */

